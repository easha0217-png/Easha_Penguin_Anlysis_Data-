import pandas as pd
import matplotlib.pyplot as pl

df = pd.read_csv('penguins.csv')

print("--- First 5 Rows ---")
print(df.head())

print("\n--- Data Structure & Non-Null Counts ---")
print(df.info())

print("\n--- Summary Statistics ---")
print(df.describe(include='all'))

print("--- Missing Values Count ---")
print(df.isnull().sum())

df_clean = df.dropna().copy()

print(f"\nOriginal shape: {df.shape}, Cleaned shape: {df_clean.shape}")

plt.figure(figsize=(8, 5))
for species_name, group in df_clean.groupby('species'):
    plt.hist(group['flipper_length_mm'], alpha=0.5, label=species_name, bins=15)

plt.title('Distribution of Flipper Length by Species')
plt.xlabel('Flipper Length (mm)')
plt.ylabel('Count')
plt.legend(title='Species')
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

plt.figure(figsize=(8, 5))
for species_name, group in df_clean.groupby('species'):
    plt.scatter(group['bill_length_mm'], group['bill_depth_mm'], label=species_name, alpha=0.7)

plt.title('Bill Length vs. Bill Depth by Species')
plt.xlabel('Bill Length (mm)')
plt.ylabel('Bill Depth (mm)')
plt.legend(title='Species')
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

plt.figure(figsize=(8, 5))
df_clean.boxplot(column='body_mass_g', by='species', grid=False, ax=plt.gca())
plt.title('Body Mass Distribution by Species')
plt.suptitle('')  # Clear default pandas title banner
plt.xlabel('Species')
plt.ylabel('Body Mass (g)')
plt.show()











